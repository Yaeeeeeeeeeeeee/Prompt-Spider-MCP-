import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {Miniflare} from 'miniflare';
import {DurableSessionStore} from '../src/mcp-store.js';
import {handleMcp} from '../src/mcp.js';

test('remote MCP discovery, privacy, durable concurrent events and exports',async()=>{
 const mf=new Miniflare({modules:true,script:'export default {fetch(){return new Response("ok")}}',compatibilityDate:'2026-07-01',d1Databases:{DB:'mcp-test'}});
 try {
  const DB=await mf.getD1Database('DB');
  const sql=await readFile(new URL('../migrations/0002_mcp.sql',import.meta.url),'utf8');
  for(const statement of sql.split(';').filter(s=>s.trim())) await DB.prepare(statement).run();
  const env={DB,MCP_AUTH_TOKEN:'test-secret'};
  let id=0;
  async function rpc(method,params={}) {
   const response=await handleMcp(new Request('https://example.test/mcp',{method:'POST',headers:{authorization:'Bearer test-secret','content-type':'application/json',accept:'application/json, text/event-stream'},body:JSON.stringify({jsonrpc:'2.0',id:++id,method,params})}),env);
   assert.equal(response.status,200);
   return (await response.json()).result;
  }
  assert.equal((await handleMcp(new Request('https://example.test/mcp'),env)).status,401);
  const init=await rpc('initialize',{protocolVersion:'2025-03-26',capabilities:{},clientInfo:{name:'test',version:'1'}});
  assert.ok(init.serverInfo);
  assert.equal((await rpc('tools/list')).tools.length,11);
  assert.equal((await rpc('resources/list')).resources.length,3);
  assert.ok((await rpc('resources/read',{uri:'spider://guide'})).contents[0].text.includes('D1'));
  assert.equal((await rpc('prompts/list')).prompts.length,1);
  const created=await rpc('tools/call',{name:'spider_create_session',arguments:{context:{source:'cloud',project_id:'AliceMedicalCase',run_id:'AliceMedicalRun',node_id:'AliceMedicalNode',simulated:false}}});
  assert.ok(!created.isError,JSON.stringify(created));
  const sessionId=created.structuredContent.id;
  assert.match(created.structuredContent.context.project_id,/^[a-f0-9]{64}$/);
  const privateContext=created.structuredContent.context;
  assert.equal(privateContext.simulated,false);
  assert.equal(created.structuredContent.source,'cloud');
  assert.equal(created.structuredContent.connection_status,'connected');
  const oauthResponse=await handleMcp(new Request('https://example.test/mcp',{method:'POST',headers:{authorization:'Bearer oauth-token','content-type':'application/json',accept:'application/json, text/event-stream'},body:JSON.stringify({jsonrpc:'2.0',id:100,method:'tools/list',params:{}})}),env,{authenticated:true});
  assert.equal(oauthResponse.status,200);
  assert.equal((await oauthResponse.json()).result.tools.length,11);
  const failed=await handleMcp(new Request('https://example.test/mcp',{method:'POST',headers:{authorization:'Bearer test-secret','content-type':'application/json',accept:'application/json, text/event-stream'},body:JSON.stringify({jsonrpc:'2.0',id:101,method:'tools/call',params:{name:'spider_create_session',arguments:{}}})}),{...env,DB:{prepare(){throw new Error('SQL secret /private/path')}}});
  const failedBody=await failed.json();
  assert.equal(failedBody.result.isError,true);
  assert.doesNotMatch(JSON.stringify(failedBody),/SQL secret|private.path/);
  const update=await rpc('tools/call',{name:'spider_update_events',arguments:{sessionId,events:[{id:'secret command',label:'secret label',route:'code'}]}});
  assert.ok(!update.isError,JSON.stringify(update));
  assert.doesNotMatch(JSON.stringify(update),/secret command|secret label/);
  const repeated=await rpc('tools/call',{name:'spider_update_events',arguments:{sessionId,events:[{id:'secret command',status:'completed'}]}});
  assert.ok(!repeated.isError,JSON.stringify(repeated));
  assert.equal((await new DurableSessionStore(DB).get(sessionId)).totalEvents,1);
  const bad=await rpc('tools/call',{name:'spider_update_events',arguments:{sessionId,events:[{id:'a',label:'a',route:'code',detail:'secret'}]}});
  assert.equal(bad.isError,true);
  const firstExport=await rpc('tools/call',{name:'spider_export_session',arguments:{sessionId,filename:'AliceMedicalCase.json'}});
  assert.ok(!firstExport.isError,JSON.stringify(firstExport));
  const imported=await rpc('tools/call',{name:'spider_import_session',arguments:{filename:firstExport.structuredContent.filename}});
  assert.ok(!imported.isError,JSON.stringify(imported));
  const replayId=imported.structuredContent.id;
  const replayUpdate=await rpc('tools/call',{name:'spider_update_events',arguments:{sessionId:replayId,events:[{id:'x',label:'x',route:'code'}]}});
  assert.equal(replayUpdate.isError,true);
  await new DurableSessionStore(DB).close(replayId);
  const project=await rpc('tools/call',{name:'spider_export_project',arguments:{sessionId,name:'AliceMedicalProject'}});
  assert.ok(!project.isError,JSON.stringify(project));
  assert.equal(project.structuredContent.format,'prompt-spider-project-files/v1');
  assert.match(firstExport.structuredContent.filename,/^[a-f0-9]{64}\.json$/);
  assert.match(project.structuredContent.filename,/^[a-f0-9]{64}\.json$/);
  const persisted=JSON.stringify(await DB.prepare('SELECT state,context FROM mcp_sessions').all())+JSON.stringify(await DB.prepare('SELECT filename,body FROM mcp_artifacts').all());
  assert.doesNotMatch(persisted,/AliceMedical|secret command|secret label/);
  const projectArtifact=await handleMcp(new Request(project.structuredContent.downloadUrl,{headers:{authorization:'Bearer test-secret'}}),env);
  assert.match((await projectArtifact.json()).name,/^[a-f0-9]{64}$/);
  const second=await rpc('tools/call',{name:'spider_create_session',arguments:{context:{source:'windows',project_id:'OtherPrivateCase'}}});
  const summaries=(await rpc('tools/call',{name:'spider_list_sessions'})).structuredContent.sessions;
  assert.deepEqual(summaries.find(item=>item.id===sessionId).context,privateContext);
  assert.equal(summaries.find(item=>item.id===second.structuredContent.id).source,'windows');
  await new DurableSessionStore(DB).close(second.structuredContent.id);
  const invalidId=await rpc('tools/call',{name:'spider_get_session',arguments:{sessionId:'AliceMedicalCase'}});
  assert.equal(invalidId.isError,true);
  env.MCP_ALLOW_PUBLIC_LABELS='true';
  const publicSession=await rpc('tools/call',{name:'spider_create_session',arguments:{context:{project_id:'PublicDemo'}}});
  assert.equal(publicSession.structuredContent.context.project_id,'PublicDemo');
  const publicExport=await rpc('tools/call',{name:'spider_export_project',arguments:{name:'public-demo'}});
  assert.equal(publicExport.structuredContent.filename,'public-demo.json');
  await new DurableSessionStore(DB).close(publicSession.structuredContent.id);
  delete env.MCP_ALLOW_PUBLIC_LABELS;
  const stores=[new DurableSessionStore(DB),new DurableSessionStore(DB)];
  await Promise.all(stores.map((store,index)=>store.updateEvents(sessionId,[{id:'parallel'+index,label:'Task '+index,route:'model'}])));
  assert.equal((await new DurableSessionStore(DB).get(sessionId)).totalEvents,3);
  const exported=await rpc('tools/call',{name:'spider_export_session',arguments:{sessionId}});
  assert.ok(!exported.isError,JSON.stringify(exported));
  assert.doesNotMatch(exported.structuredContent.downloadUrl,/test-secret/);
  const artifact=await handleMcp(new Request(exported.structuredContent.downloadUrl,{headers:{authorization:'Bearer test-secret'}}),env);
  assert.equal((await artifact.json()).events.length,3);
  await DB.prepare('UPDATE mcp_sessions SET updated_at=? WHERE id=?').bind(Date.now()-360000,sessionId).run();
  const stale=await stores[1].get(sessionId);
  assert.equal(stale.connection_status,'timed_out');
  assert.equal(stale.status,'live');
  assert.equal(stale.context.node_id,privateContext.node_id);
  await stores[0].close(sessionId);
  assert.equal((await stores[1].list()).length,0);
  assert.equal((await DB.prepare('SELECT closed FROM mcp_sessions WHERE id=?').bind(sessionId).first()).closed,1);
 } finally {await mf.dispose();}
});
