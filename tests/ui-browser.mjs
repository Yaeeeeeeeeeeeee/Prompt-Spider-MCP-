// Separate real-browser integration check: npm run test:browser (build first).
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { localWorker, credentials, sample } from './helpers/worker.js';
const require=createRequire(import.meta.url);
const { chromium }=require('playwright');
const worker=await localWorker();
let browser;
let checks=0;
const check=(condition,message)=>{assert.ok(condition,message);checks++;console.log(`ok ${checks} - ${message}`);};
try {
 let rpcId=0;
 async function tool(name,args){const response=await worker.request('/mcp',{role:'mcp',method:'POST',headers:{Accept:'application/json, text/event-stream'},body:{jsonrpc:'2.0',id:++rpcId,method:'tools/call',params:{name,arguments:args}}});assert.equal(response.status,200);const body=await response.json();assert.ok(!body.result?.isError,JSON.stringify(body));return body.result.structuredContent;}
 // Explicitly simulated records in a disposable local D1 database, never production.
 const session=await tool('spider_create_session',{context:{source:'cloud',project_id:'browser-project',node_id:'browser-node',simulated:true}});
 await tool('spider_update_events',{sessionId:session.id,events:[{id:'browser-task',label:'Browser task',route:'code',status:'running'}]});
 await tool('spider_update_events',{sessionId:session.id,events:[{id:'browser-task',status:'completed'}]});
 await tool('spider_complete_session',{sessionId:session.id,status:'completed'});
 for(const source of ['windows','cloud']){const response=await worker.request('/api/events',{role:source,method:'POST',body:sample({source,run_id:`browser-${source}`})});assert.ok(response.ok,await response.text());}
 const origin=(await worker.mf.ready).origin;
 browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1280,height:900}});
 const page=await context.newPage();
 const errors=[],csp=[],urls=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(/Content Security Policy|Refused to (execute|apply|load)/i.test(message.text()))csp.push(message.text());});
 page.on('request',request=>urls.push(request.url()));
 await page.goto(origin);
 await page.locator('#credential').fill(credentials.SPIDER_READ_TOKEN);
 await page.locator('#connect').click();
 await page.waitForFunction(()=>document.querySelectorAll('#runs .run').length===3);
 check(await page.locator('#run-count').textContent()==='3','real Worker merges one MCP session and both simulated V1 sources');
 check(await page.locator('#runs .simulation').count()===3,'every simulated MCP and V1 card displays SIMULATED');
 check(await page.locator('#credential').inputValue()==='','credential input cleared after connect');
 await page.locator('#source').selectOption('windows');
 await page.waitForFunction(()=>document.querySelectorAll('#runs .run').length===1);
 check((await page.locator('#runs').textContent()).includes('browser-windows'),'source filtering shows Windows run');
 await page.locator('#source').selectOption('cloud');
 await page.waitForFunction(()=>document.querySelectorAll('#runs .run').length===2);
 check(await page.locator('#run-count').textContent()==='2','cloud filter preserves MCP session and V1 run');
 await page.locator('#runs .run').filter({hasText:session.id}).click();
 await page.waitForFunction(()=>!document.querySelector('#replay').hidden&&document.querySelectorAll('#timeline li').length>0);
 check((await page.locator('#run-status').textContent()).includes('completed'),'selected MCP snapshot and replay show explicit completion');
 await page.locator('#position').evaluate(input=>{input.value='0';input.dispatchEvent(new Event('input',{bubbles:true}));});
 check((await page.locator('#replay-state').textContent()).includes('Historical'),'slider enters read-only historical replay');
 await page.locator('#latest').click();
 check((await page.locator('#replay-state').textContent()).includes('Latest'),'jump to latest restores latest recorded state');
 await page.locator('#position').evaluate(input=>{input.value='0';input.dispatchEvent(new Event('input',{bubbles:true}));});
 await page.locator('#play').click();
 await page.waitForFunction(()=>Number(document.querySelector('#position').value)>0);
 check(Number(await page.locator('#position').inputValue())>0,'playback advances actual recorded time');
 await page.locator('#latest').click();
 check((await page.locator('#run-meta').textContent()).includes('1 completed'),'actual completed event progress appears');
 check((await page.locator('#run-meta').textContent()).includes('SIMULATED'),'selected simulated session detail stays visibly marked');
 const canvasDrawn=await page.locator('#spider').evaluate(canvas=>Array.from(canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data).some((value,index)=>index%4===3&&value>0));
 check(canvasDrawn,'original spider renderer draws pixels in Chromium');
 await mkdir('.build',{recursive:true});
 await page.screenshot({path:'.build/dashboard-browser.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile viewport has no horizontal overflow');
 await page.screenshot({path:'.build/dashboard-browser-mobile.png',fullPage:true});
 await page.setViewportSize({width:1280,height:900});
 await context.setOffline(true);
 await page.waitForFunction(()=>document.querySelector('#connection').textContent.includes('Offline'));
 check((await page.locator('#detail-title').textContent())===session.id,'offline state retains clearly identified recorded history');
 await context.setOffline(false);
 await page.waitForFunction(()=>document.querySelector('#connection').textContent.includes('Connected'));
 await page.locator('#disconnect').click();
 check(!(await page.locator('body').textContent()).includes(session.id),'disconnect removes selected private session from DOM');
 check(await page.locator('#timeline li').count()===0,'disconnect clears event timeline');
 await page.locator('#credential').fill('invalid-reader');
 await page.locator('#connect').click();
 await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('Authentication expired or rejected'));
 check(await page.locator('#credential').inputValue()===''&&await page.locator('#runs .run').count()===0,'bad reader rejection clears credential and private results');
 check((await page.evaluate(()=>Object.keys(localStorage).length+Object.keys(sessionStorage).length))===0,'browser persistent storage remains empty');
 check(!urls.some(url=>url.includes(credentials.SPIDER_READ_TOKEN)||url.includes('invalid-reader')),'credentials never appear in request URLs');
 check(errors.length===0,`no browser JavaScript errors: ${errors.join('; ')}`);
 check(csp.length===0,`no Content Security Policy violations: ${csp.join('; ')}`);
 console.log(`Browser integration: ${checks} checks passed (real Chromium + local Worker/D1).`);
} finally {await browser?.close();await worker.close();}
